    Connection watch(Connection target) {
        return (Connection) Proxy.newProxyInstance(Connection.class.getClassLoader(), new Class<?>[]{Connection.class}, (p, m, args) -> {
            if (Set.of("prepareStatement", "createStatement", "prepareCall").contains(m.getName())) {
                rowStatements.incrementAndGet();
                throw new AssertionError("Codegen must not execute business-row SQL");
            }
            try {
                return m.invoke(target, args);
            } catch (InvocationTargetException e) {
                throw e.getCause();
            }
        });
    }

