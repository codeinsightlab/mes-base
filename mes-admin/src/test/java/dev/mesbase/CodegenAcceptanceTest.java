    @Configuration(proxyBeanMethods = false)
    @EnableTransactionManagement(proxyTargetClass = true)
    static class GeneratedTransactions {
    }

    private AnnotationConfigApplicationContext generatedContext(URLClassLoader loader, Class<?> mapperType,
                                                                Class<?> serviceType, DataSource source,
                                                                String transactionManager) {
        var context = new AnnotationConfigApplicationContext();
        context.setClassLoader(loader);
        context.getEnvironment().getPropertySources()
                .addFirst(new MapPropertySource("fixture", Map.of("mes.platform.enabled", "true", "mes.system.enabled", "true")));
        var manager = new OwnedTransactionManager(source);
        var factory = PersistenceFactories.create(source, Set.of(mapperType), PersistenceFactories::pagination, manager::verifyAccess);
        var template = new SqlSessionTemplate(factory);
        Object mapper = template.getMapper(mapperType);
        AtomicBoolean failAfterWrite = new AtomicBoolean();
        Object watched = Proxy.newProxyInstance(loader, new Class<?>[]{mapperType}, (proxy, method, args) -> {
            if (failAfterWrite.get() && method.getName().equals("selectByPrimaryKey")) {
                throw new IllegalStateException("TEST ONLY failure after insert");
            }
            try {
                return method.invoke(mapper, args);
            } catch (InvocationTargetException exception) {
                throw exception.getCause();
            }
        });
        context.register(GeneratedTransactions.class);
        context.registerBean(transactionManager, OwnedTransactionManager.class, () -> manager);
        context.registerBean(AtomicBoolean.class, () -> failAfterWrite);
        var definition = new RootBeanDefinition();
        definition.setBeanClass(mapperType);
        definition.setInstanceSupplier(() -> watched);
        context.registerBeanDefinition("generatedMapper", definition);
        context.registerBeanDefinition("generatedService", new RootBeanDefinition(serviceType));
        context.refresh();
        return context;
    }
