package dev.mesbase;

import dev.mesbase.platform.codegen.CodegenCli;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.DriverManager;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assertions.assertFalse;

/**
 * TEST ONLY: two-column H2 metadata fixture; never connects to a managed Factory.
 */
class CodegenPersonAcceptanceTest {
    @Test
    void generatesPersonFromJdbcMetadataWithACompiledMenu() throws Exception {
        Path root = Path.of("target/codegen-person").toAbsolutePath();
        Files.createDirectories(root);
        String url = "jdbc:h2:file:" + root.resolve("metadata") + ";DATABASE_TO_LOWER=TRUE";
        try (var connection = DriverManager.getConnection(url, "sa", "");
             var statement = connection.createStatement()) {
            statement.execute("CREATE TABLE IF NOT EXISTS person (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(64) NOT NULL)");
            statement.execute("COMMENT ON COLUMN person.id IS '编号'");
            statement.execute("COMMENT ON COLUMN person.name IS '姓名'");
            try (var columns = connection.getMetaData().getColumns(null, null, "person", null)) {
                int count = 0;
                while (columns.next()) count++;
                assertEquals(2, count);
            }
        }
        Path config = root.resolve("fixture.properties");
        Files.writeString(config, "mes.codegen.default-datasource=person-fixture\n"
                + "mes.codegen.profiles.person-fixture.url=" + url + "\n"
                + "mes.codegen.profiles.person-fixture.username=sa\n"
                + "mes.codegen.profiles.person-fixture.password=\n"
                + "mes.codegen.profiles.person-fixture.driver-class-name=org.h2.Driver\n");
        Path frontend = Path.of("../mes-base-ui/target/codegen-person").toAbsolutePath().normalize();
        String[] arguments = {"--config=" + config, "--datasource=person-fixture", "--table=person",
                "--module=acceptance", "--business-name=人员", "--overwrite",
                "--output=" + root.resolve("backend"), "--frontend-root=" + frontend};
        assertEquals(0, CodegenCli.run(arguments));
        Path javaRoot = root.resolve("backend/mes-business/src/main/java/dev/mesbase/modules/acceptance");
        String service = Files.readString(javaRoot.resolve("service/impl/PersonServiceImpl.java"));
        assertTrue(service.contains("private final PersonMapper mapper;"));
        assertTrue(service.contains("@Transactional(transactionManager = \"businessTransactionManager\""));
        assertFalse(service.contains("persistence.transaction("));
        assertFalse(service.contains("PersonVo"));
        assertFalse(service.contains("public final class PersonServiceImpl"));
        assertTrue(service.contains("package dev.mesbase.modules.acceptance.service.impl;\n\nimport "));
        String controller = Files.readString(javaRoot.resolve("controller/PersonController.java"));
        assertTrue(controller.contains("private static PersonVo toView(PersonEntity row)"));
        String mapper = Files.readString(javaRoot.resolve("dao/PersonMapper.java"));
        assertFalse(mapper.contains("factory"));
        String xml = Files.readString(root.resolve(
                "backend/mes-business/src/main/resources/dev/mesbase/modules/acceptance/dao/PersonMapper.xml"));
        assertFalse(xml.contains("distinct"));
        String example = Files.readString(root.resolve(
                "backend/mes-business/src/main/java/dev/mesbase/modules/acceptance/domain/PersonExample.java"));
        assertFalse(example.contains("distinct"));
        assertFalse(example.contains("setDistinct"));
        assertFalse(example.contains("isDistinct"));
        assertTrue(xml.contains("from person"));
        assertTrue(xml.contains("insert into person"));
        assertTrue(xml.contains("update person"));
        assertTrue(xml.contains("id, name"));
        assertFalse(xml.contains("&quot;"));
        assertFalse(xml.contains("\"public\"."));
        assertFalse(xml.contains("public.person"));
        assertTrue(service.contains("example.setOrderByClause(\"id\")"));
        String permissions = Files.readString(javaRoot.resolve("controller/PersonPermissions.java"));
        assertTrue(Files.readString(javaRoot.resolve("domain/PersonResource.java")).contains("business:person"));
        assertTrue(permissions.contains("PersonResource.PREFIX"));
        for (String action : new String[]{"read", "create", "update", "delete"}) {
            assertTrue(permissions.contains("\":" + action + "\""));
        }
        String sql = Files.readString(root.resolve("backend/mes-business/docs/generated/acceptance/person-menu.sql"));
        assertTrue(sql.contains("INSERT INTO sys_menu"));
        assertTrue(sql.contains("business:person:delete"));
        assertTrue(controller.contains("permission = PersonPermissions.DELETE"));
        assertTrue(service.contains("mapper.deleteByExample(example)"));
        assertTrue(Files.readString(frontend.resolve("src/api/acceptance/person.ts")).contains("delids: removeIds"));
        String page = Files.readString(frontend.resolve("src/views/acceptance/person/index.vue"));
        assertTrue(page.contains("CrudPage"));
        assertTrue(page.contains("key: 'id'"));
        assertTrue(page.contains("key: 'name'"));
        assertTrue(page.contains("label: '姓名'"));
        assertTrue(page.contains("maxLength: 64"));
        String menu = Files.readString(frontend.resolve("src/menus/acceptance/person.json"));
        assertTrue(menu.contains("\"path\": \"/acceptance/person\""));
        assertTrue(menu.contains("\"permission\": \"business:person:read\""));
        assertTrue(menu.contains("\"permissionScope\": \"factory\""));
    }
}
