    @AfterEach
    void close() throws Exception {
        if (registry != null) registry.close();
        if (dataSource != null) dataSource.getConnection().close();
    }

    @Test
    void successfulRequestReplaysSameSetAndSameKeyWithDifferentContentConflicts() {
        var original = command("request-1", "hash-1", "2");
        var created = create(original);
        var replay = create(original);
        assertEquals(created.stream().map(row -> row.workorder().getId()).toList(),
                replay.stream().map(row -> row.workorder().getId()).toList());
        assertEquals(2, jdbc.queryForObject("SELECT COUNT(*) FROM workorder", Integer.class));

        var altered = command("request-1", "hash-2", "3");
        assertEquals(ErrorCode.RESOURCE_CONFLICT,
                assertThrows(FoundationException.class, () -> create(altered)).code());
        assertEquals(2, jdbc.queryForObject("SELECT COUNT(*) FROM workorder", Integer.class));
    }

    @Test
    void concurrentSameRequestReturnsOneCommittedSet() throws Exception {
        var command = command("request-concurrent", "hash-concurrent", "2");
        var start = new CountDownLatch(1);
        numberingGate = new CountDownLatch(2);
        try (var executor = Executors.newFixedThreadPool(2)) {
            var first = executor.submit(() -> {
                start.await();
                return create(command);
            });
            var second = executor.submit(() -> {
                start.await();
                return create(command);
            });
            start.countDown();
            var left = first.get();
            var right = second.get();
            assertEquals(left.stream().map(row -> row.workorder().getId()).toList(),
                    right.stream().map(row -> row.workorder().getId()).toList());
            assertEquals(2, jdbc.queryForObject("SELECT COUNT(*) FROM workorder", Integer.class));
        }
    }

    @Test
    void laterMaterialSaveFailureRollsBackEveryWorkOrderHeader() {
        var calls = new AtomicInteger();
        doAnswer(call -> {
            var order = call.getArgument(0, WorkorderEntity.class);
            var row = new dev.mesbase.business.production.domain.MesWorkorderMaterialEntity();
            row.setWorkorderId(order.getId());
            row.setMaterialId(2L);
            row.setUnitId(1L);
            row.setTotalRequiredQty(BigDecimal.ONE);
            row.setPlannedQty(order.getPlannedQty());
            row.setWarehouseIds("[]");
            row.setWorkCenter("");
            row.setRevision(1L);
            row.setStatus("ENABLED");
            row.setUpdatedAt(java.time.LocalDateTime.now());
            row.setBomId(51L);
            row.setBomBaseQty(BigDecimal.ONE);
            row.setBomComponentQty(BigDecimal.ONE);
            row.setOutputUnitId(1L);
            row.setLineNo(1);
            row.setBomItemId(10L);
            row.setManuallyAdjusted(false);
            assertEquals(1, materialRows.insert(row));
            if (calls.incrementAndGet() == 2) throw new FoundationException(ErrorCode.RESOURCE_CONFLICT);
            return null;
        }).when(materialDemands).replace(any(WorkorderEntity.class), any(WorkorderMaterialModels.Save.class));

        assertEquals(ErrorCode.RESOURCE_CONFLICT, assertThrows(FoundationException.class,
                () -> create(command("request-fail", "hash-fail", "2"))).code());
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM workorder", Integer.class));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM mes_workorder_material", Integer.class));
        verify(materialDemands, org.mockito.Mockito.times(2))
                .replace(any(WorkorderEntity.class), any(WorkorderMaterialModels.Save.class));
    }

    @Test
    void ordinaryLocalCreationKeepsExistingTransactionAndHasNoBomBuildLink() {
        var values = command("ordinary", "ordinary", "2").orders().getFirst().values();
        var created = FactoryContext.withScope(scope, () -> service.create(values));
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM workorder", Integer.class));
        assertEquals(null, created.workorder().getBomBuildId());
        assertEquals(null, created.workorder().getBomBuildParentWorkorderId());
    }

    private List<WorkOrderModels.Detail> create(WorkOrderService.BomBuildCommand command) {
        return FactoryContext.withScope(scope, () -> service.createBomBuild(command));
    }

    private static WorkOrderService.BomBuildCommand command(String requestId, String requestHash, String quantity) {
        var values = new WorkOrderModels.Save(null, 1L, new BigDecimal(quantity), null, null, null, null, null,
                null, null, "RULE", new WorkorderMaterialModels.Save(0L, 51L, 7L, List.of(), "", true,
                List.of(new WorkorderMaterialModels.Line(null, 10L, 2L, 1L, new BigDecimal(quantity), false)), true));
        return new WorkOrderService.BomBuildCommand("build-" + requestId, requestId, requestHash, List.of(
                new WorkOrderService.BomBuildOrder(values, "ROOT", null, null),
                new WorkOrderService.BomBuildOrder(values, "/10", "ROOT", 10L)));
    }
